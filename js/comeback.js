// ความลำบากของชีวิต 0–1 (ใช้เพิ่มน้ำหนักเหตุการณ์พลิกชีวิต)
function struggle(s) {
  let v = 0;
  const soul = s.awakened ? SOUL_BY_ID[s.souls[0]] : null;
  if (soul && soul.tier <= 2) v += 0.35;
  if (s.awakened && !isCultivator(s)) v += 0.35;
  if (isCultivator(s) && s.age >= 14 && lvl(s) < s.age * 0.9) v += 0.2;
  if (s.familyTier <= 2) v += 0.15;
  if (s.disabilities.length) v += 0.1 * s.disabilities.length;
  if (s.mood < 30) v += 0.1;
  return Math.min(1, v);
}

